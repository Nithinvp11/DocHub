-- Create foreign key for document if not exists
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'SyncEvent_documentId_fkey'
  ) THEN
    ALTER TABLE "SyncEvent" ADD CONSTRAINT "SyncEvent_documentId_fkey" 
      FOREIGN KEY ("documentId") REFERENCES "Document"("id") ON DELETE CASCADE;
  END IF;
END $$;

-- Create indexes for sync event queries
CREATE INDEX IF NOT EXISTS "SyncEvent_documentId_idx" ON "SyncEvent"("documentId");
