-- Step 6: Create SyncQueue table for background processing
CREATE TABLE IF NOT EXISTS "SyncQueue" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "documentId" TEXT NOT NULL,
  "workspaceId" TEXT NOT NULL,
  "operation" TEXT NOT NULL,
  "priority" INTEGER NOT NULL DEFAULT 0,
  "status" TEXT NOT NULL DEFAULT 'pending',
  "attemptCount" INTEGER NOT NULL DEFAULT 0,
  "maxAttempts" INTEGER NOT NULL DEFAULT 3,
  "error" TEXT,
  "metadata" JSONB,
  "scheduledAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "startedAt" TIMESTAMP(3),
  "completedAt" TIMESTAMP(3),
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  
  CONSTRAINT "SyncQueue_documentId_fkey" FOREIGN KEY ("documentId") 
    REFERENCES "Document"("id") ON DELETE CASCADE,
  CONSTRAINT "SyncQueue_workspaceId_fkey" FOREIGN KEY ("workspaceId") 
    REFERENCES "Workspace"("id") ON DELETE CASCADE
);

-- Create indexes for sync queue
CREATE INDEX IF NOT EXISTS "SyncQueue_status_priority_idx" ON "SyncQueue"("status", "priority" DESC);
CREATE INDEX IF NOT EXISTS "SyncQueue_documentId_idx" ON "SyncQueue"("documentId");
CREATE INDEX IF NOT EXISTS "SyncQueue_workspaceId_idx" ON "SyncQueue"("workspaceId");
CREATE INDEX IF NOT EXISTS "SyncQueue_scheduledAt_idx" ON "SyncQueue"("scheduledAt");

-- Step 7: Create GitHubWebhook table for webhook management
